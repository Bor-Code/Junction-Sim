def find_blender_executable() -> str | None:
    found = shutil.which("blender")
    if found:
        return found
    if sys.platform == "win32":
        candidates = [
            r"C:\Program Files\Blender Foundation\Blender 5.2\blender.exe",
            r"C:\Program Files\Blender Foundation\Blender 5.1\blender.exe",
            r"C:\Program Files\Blender Foundation\Blender 5.0\blender.exe",
            r"C:\Program Files\Blender Foundation\Blender 4.3\blender.exe",
            r"C:\Program Files\Blender Foundation\Blender 4.2\blender.exe",
        ]
        for c in candidates:
            if Path(c).is_file():
                return c
        base = Path(r"C:\Program Files\Blender Foundation")
        if base.is_dir():
            for p in base.glob("**/blender.exe"):
                if p.is_file():
                    return str(p)
    elif sys.platform == "darwin":
        mac_app = Path("/Applications/Blender.app/Contents/MacOS/Blender")
        if mac_app.is_file():
            return str(mac_app)
    return None


def compile_blender_scene(
    script_path: str | Path,
    blend_path: str | Path,
    blender_bin: str | None = None,
) -> bool:
    bin_path = blender_bin or find_blender_executable()
    if not bin_path or not Path(bin_path).is_file():
        return False

    script_resolved = str(Path(script_path).resolve())
    blend_resolved = str(Path(blend_path).resolve())

    cmd = [
        bin_path,
        "-b",
        "--python",
        script_resolved,
        "--",
        "--save-blend",
        blend_resolved,
    ]
    res = subprocess.run(cmd, capture_output=True, check=False)
    return res.returncode == 0 and Path(blend_resolved).is_file()


