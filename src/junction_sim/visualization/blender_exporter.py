def export_blender_script(
    results: Sequence[StepResult],
    intersection: Intersection,
    signal_plan: SignalPlan,
    destination: str | Path | TextIO,
    controller_name: str = "unknown",
    scenario_name: str = "custom",
    seed: int | None = None,
    fps: int = 24,
    substep_dt: float = 0.2,
    blend_destination: str | Path | None = None,
) -> None:
    blend_dest_str = str(blend_destination) if blend_destination else None
    content = generate_blender_script(
        results=results,
        intersection=intersection,
        signal_plan=signal_plan,
        controller_name=controller_name,
        scenario_name=scenario_name,
        seed=seed,
        fps=fps,
        substep_dt=substep_dt,
        blend_destination=blend_dest_str,
    )

    if hasattr(destination, "write"):
        destination.write(content)
    else:
        dest_path = Path(str(destination))
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        dest_path.write_text(content, encoding="utf-8")
        if blend_destination:
            compile_blender_scene(dest_path, blend_destination)
